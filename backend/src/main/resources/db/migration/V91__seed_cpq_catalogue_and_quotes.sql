-- E08 closure seed — make the CPQ schema visible in a runnable environment.
--
-- V90 created the production-grade CPQ tables, constraints, RLS and RBAC. This
-- migration populates tenant product catalogues and representative quote
-- transactions from the already-seeded opportunity price list so fresh Docker
-- environments do not expose an empty commerce workspace.

insert into cpq.product
  (tenant_id, code, name, description, product_family, category, unit_of_measure,
   is_active, is_subscription, attributes, default_cost)
select distinct e.tenant_id,
       e.product_code,
       e.product_name,
       'Seeded from the opportunity price list to bootstrap the governed CPQ catalogue.',
       case
         when e.product_code like 'PLT-%' then 'Platform'
         when e.product_code like 'MOD-%' then 'Module'
         when e.product_code like 'SVC-%' then 'Services'
         when e.product_code like 'SUP-%' then 'Support'
         else 'Commercial'
       end,
       case
         when e.recurring then 'Subscription'
         when e.product_code like 'SVC-%' then 'Professional Services'
         else 'One-time'
       end,
       e.unit_of_measure,
       e.active,
       e.recurring,
       jsonb_build_object('source', 'pipeline.price_book_entry', 'bootstrap', true),
       e.unit_cost
from pipeline.price_book_entry e
on conflict (tenant_id, code) do update
  set name = excluded.name,
      product_family = excluded.product_family,
      category = excluded.category,
      unit_of_measure = excluded.unit_of_measure,
      is_active = excluded.is_active,
      is_subscription = excluded.is_subscription,
      default_cost = excluded.default_cost,
      updated_at = now(),
      version = cpq.product.version + 1;

insert into cpq.price_book
  (tenant_id, code, name, currency_code, status, is_default, activated_at)
select b.tenant_id,
       'STANDARD-' || upper(left(replace(b.id::text, '-', ''), 8)),
       b.name,
       'USD',
       case when b.active then 'ACTIVE' else 'ARCHIVED' end,
       b.is_default,
       case when b.active then now() else null end
from pipeline.price_book b
on conflict (tenant_id, code) do update
  set name = excluded.name,
      status = excluded.status,
      is_default = excluded.is_default,
      activated_at = excluded.activated_at,
      updated_at = now(),
      version = cpq.price_book.version + 1;

insert into cpq.price_book_entry
  (tenant_id, price_book_id, product_id, unit_price, unit_cost, currency_code,
   pricing_method, effective_from, effective_to, is_active)
select e.tenant_id,
       cb.id,
       p.id,
       e.list_price,
       e.unit_cost,
       'USD',
       'LIST',
       date '2026-01-01',
       null,
       e.active
from pipeline.price_book_entry e
join pipeline.price_book pb on pb.tenant_id = e.tenant_id and pb.id = e.price_book_id
join cpq.price_book cb on cb.tenant_id = pb.tenant_id and cb.name = pb.name
join cpq.product p on p.tenant_id = e.tenant_id and p.code = e.product_code
where not exists (
  select 1 from cpq.price_book_entry existing
  where existing.tenant_id = e.tenant_id
    and existing.price_book_id = cb.id
    and existing.product_id = p.id
    and existing.is_active
    and daterange(existing.effective_from, existing.effective_to, '[]') && daterange(date '2026-01-01', null, '[]')
);

insert into cpq.approval_policy
  (tenant_id, code, name, trigger_type, applies_to, threshold_pct, margin_floor_pct,
   product_category, approver_role, priority)
select t.id, seed.code, seed.name, seed.trigger_type, seed.applies_to, seed.threshold_pct,
       seed.margin_floor_pct, seed.product_category, seed.approver_role, seed.priority
from platform.tenant t
cross join (values
  ('DISC-15-SUBSCRIPTION', 'Subscription discount above 15%', 'DISCOUNT_PCT', 'QUOTE', 15.0000::numeric, null::numeric, 'Subscription', 'SALES_MANAGER', 20),
  ('MARGIN-35-SERVICES', 'Services margin floor 35%', 'MARGIN_FLOOR', 'QUOTE', null::numeric, 35.0000::numeric, 'Professional Services', 'FINANCE', 30)
) as seed(code, name, trigger_type, applies_to, threshold_pct, margin_floor_pct, product_category, approver_role, priority)
on conflict (tenant_id, code) do nothing;

