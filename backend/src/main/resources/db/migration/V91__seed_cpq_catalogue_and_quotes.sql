insert into cpq.guided_question
  (tenant_id, questionnaire, code, sequence_no, prompt, help_text, answer_type)
select t.id, 'DEFAULT', seed.code, seed.sequence_no, seed.prompt, seed.help_text, 'SINGLE_SELECT'
from platform.tenant t
cross join (values
  ('PRIMARY_GOAL', 10, 'What is the customer buying motion?', 'Guides catalogue recommendations by commercial intent.'),
  ('SERVICE_NEED', 20, 'How much implementation help is needed?', 'Helps attach services without burying them in the product list.')
) as seed(code, sequence_no, prompt, help_text)
on conflict (tenant_id, questionnaire, code) do nothing;

insert into cpq.guided_answer_option
  (tenant_id, question_id, code, label, filter_category, filter_attribute_name,
   filter_attribute_value, recommended_product_id, weight, sort_order)
select q.tenant_id,
       q.id,
       seed.code,
       seed.label,
       seed.filter_category,
       null,
       null,
       p.id,
       seed.weight,
       seed.sort_order
from cpq.guided_question q
join (values
  ('PRIMARY_GOAL', 'CORE_CRM', 'Core CRM platform', 'Subscription', 'PLT-CORE', 90, 10),
  ('PRIMARY_GOAL', 'ADVANCED_REVENUE', 'Advanced revenue operations', 'Subscription', 'PLT-ADV', 100, 20),
  ('SERVICE_NEED', 'IMPLEMENTATION', 'Implementation support required', 'Professional Services', 'SVC-IMPL', 80, 10),
  ('SERVICE_NEED', 'TRAINING', 'Enablement and training required', 'Professional Services', 'SVC-TRAIN', 70, 20)
) as seed(question_code, code, label, filter_category, product_code, weight, sort_order)
  on seed.question_code = q.code
join cpq.product p on p.tenant_id = q.tenant_id and p.code = seed.product_code
on conflict (tenant_id, question_id, code) do nothing;

