insert into cpq.quote
  (id, tenant_id, quote_number, quote_group_id, version_number, is_active_version,
   opportunity_id, account_id, contact_id, price_book_id, owner_id, name, status,
   approval_status, currency_code, subtotal, discount_total, tax_total, grand_total,
   corporate_currency_code, corporate_grand_total, fx_rate, fx_rate_date, cost_total,
   margin_amount, margin_pct, quote_discount_pct, valid_from, expires_at, sent_at,
   accepted_at, document_ref, document_version, change_reason)
select s.id,
       o.tenant_id,
       s.quote_number,
       s.group_id,
       1,
       true,
       o.id,
       o.account_id,
       c.id,
       pb.id,
       o.owner_id,
       s.name,
       s.status,
       s.approval_status,
       'USD',
       s.subtotal,
       s.discount_total,
       0,
       s.grand_total,
       'USD',
       s.grand_total,
       1,
       current_date,
       round(s.grand_total * 0.62, 2),
       round(s.grand_total * (s.margin_pct / 100), 2),
       s.margin_pct,
       round((s.discount_total / nullif(s.subtotal, 0)) * 100, 4),
       current_date,
       now() + s.expiry_interval,
       case when s.status in ('SENT','ACCEPTED','REJECTED','ORDERED') then now() - interval '1 day' else null end,
       case when s.status = 'ACCEPTED' then now() else null end,
       case when s.status in ('SENT','ACCEPTED') then 'local://quotes/' || s.quote_number || '.pdf' else null end,
       case when s.status in ('SENT','ACCEPTED') then 1 else null end,
       'Seeded CPQ transaction for read-workspace verification.'
from quote_seed s
join sales.opportunity o on o.id = s.opportunity_id
join cpq.price_book pb on pb.tenant_id = o.tenant_id and pb.status = 'ACTIVE' and pb.is_default
left join lateral (
  select id from crm.contact c
  where c.tenant_id = o.tenant_id and c.account_id = o.account_id and c.deleted_at is null
  order by c.created_at
  limit 1
) c on true
on conflict (tenant_id, quote_number) do nothing;

